"""Incremental knowledge-base ingest into ``kb_documents`` / ``kb_chunks`` (ADR 0004).

A document whose hash (file, chunker version and embedding model) is unchanged is skipped
without chunking. Otherwise its chunks are matched to the stored ones by ``content_hash``:
matched rows keep their id and embedding and only move to the new position, new chunks
are embedded in batches, unmatched rows are deleted. Documents whose file is gone are
deleted with their chunks. ``tsv`` is generated by PostgreSQL (the ``simple`` config).

``python -m rozmova_engine.rag.ingest [kb_dir]`` (``make ingest``) runs it once.
"""

import argparse
import asyncio
import hashlib
import sys
from collections import defaultdict
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

import structlog
from sqlalchemy import delete, func, select
from sqlalchemy.ext.asyncio import AsyncEngine, AsyncSession

from rozmova_core.db import create_engine, create_session_factory
from rozmova_core.log import configure_logging
from rozmova_core.models import KbChunk, KbDocument
from rozmova_core.settings import Settings
from rozmova_engine.rag.chunking import Chunk, chunk_markdown
from rozmova_engine.rag.embeddings import Embedder, FakeEmbedder, OpenAIEmbedder

log = structlog.get_logger(__name__)

# Bump when chunking changes, so every document is re-chunked on the next ingest.
CHUNKER_VERSION = "1"
# pg_try_advisory_lock key: one ingest at a time across processes (admin-api replicas, CLI).
INGEST_LOCK_KEY = 0x524F5A4B42  # "ROZKB"
# The developer README in kb/ describes the layout and is not knowledge.
EXCLUDED_FILES = frozenset({"README.md"})


@dataclass(slots=True)
class IngestReport:
    documents_added: int = 0
    documents_updated: int = 0
    documents_unchanged: int = 0
    documents_deleted: int = 0
    chunks_embedded: int = 0
    chunks_reused: int = 0
    chunks_deleted: int = 0
    # Another process held the ingest lock, so this run did nothing.
    skipped_locked: bool = False


def kb_files(root: Path) -> list[Path]:
    return sorted(
        path for path in root.rglob("*.md") if path.is_file() and path.name not in EXCLUDED_FILES
    )


def read_kb(root: Path) -> list[tuple[str, str, str]]:
    """``(source_path, file stem, Markdown)`` for every KB file; blocking, run in a thread."""
    if not root.is_dir():
        raise FileNotFoundError(f"knowledge base directory {root} does not exist")
    return [
        (path.relative_to(root).as_posix(), path.stem, path.read_text(encoding="utf-8"))
        for path in kb_files(root)
    ]


def document_hash(markdown: str, embedding_model: str) -> str:
    payload = "\x1f".join((CHUNKER_VERSION, embedding_model, markdown))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


async def ingest_directory(root: Path, engine: AsyncEngine, embedder: Embedder) -> IngestReport:
    """Bring the KB tables in line with the Markdown files under ``root``."""
    documents = await asyncio.to_thread(read_kb, root)
    report = IngestReport()
    factory = create_session_factory(engine)

    async with engine.connect() as lock_conn:
        locked = await lock_conn.scalar(select(func.pg_try_advisory_lock(INGEST_LOCK_KEY)))
        if not locked:
            log.info("kb_ingest_skipped", reason="another ingest holds the lock")
            report.skipped_locked = True
            return report
        try:
            seen = {source_path for source_path, _, _ in documents}
            for source_path, stem, markdown in documents:
                async with factory() as db:
                    await _ingest_document(db, source_path, markdown, stem, embedder, report)
            async with factory() as db, db.begin():
                result = await db.execute(
                    delete(KbDocument)
                    .where(KbDocument.source_path.not_in(seen))
                    .returning(KbDocument.source_path)
                )
                removed = list(result.scalars())
            report.documents_deleted = len(removed)
            if removed:
                log.info("kb_documents_deleted", source_paths=removed)
        finally:
            await lock_conn.execute(select(func.pg_advisory_unlock(INGEST_LOCK_KEY)))
            await lock_conn.commit()

    log.info("kb_ingest_done", **_report_fields(report))
    return report


async def _ingest_document(
    db: AsyncSession,
    source_path: str,
    markdown: str,
    default_title: str,
    embedder: Embedder,
    report: IngestReport,
) -> None:
    doc_hash = document_hash(markdown, embedder.model)
    document = await db.scalar(select(KbDocument).where(KbDocument.source_path == source_path))
    if document is not None and document.content_hash == doc_hash:
        report.documents_unchanged += 1
        return

    chunks = chunk_markdown(markdown, default_title=default_title, hash_salt=embedder.model)
    stored: dict[str, list[KbChunk]] = defaultdict(list)
    if document is not None:
        rows = await db.scalars(
            select(KbChunk).where(KbChunk.document_id == document.id).order_by(KbChunk.position)
        )
        for row in rows:
            stored[row.content_hash].append(row)
    # Close the read transaction: no connection is held while the embedding API runs.
    await db.commit()

    kept, fresh = _match(chunks, stored)
    vectors = await embedder.embed([chunk.text for _, chunk in fresh]) if fresh else []
    stale = [row for rows in stored.values() for row in rows]

    async with db.begin():
        title = _title(chunks, default_title)
        if document is None:
            document = KbDocument(title=title, source_path=source_path, content_hash=doc_hash)
            db.add(document)
            await db.flush()
            report.documents_added += 1
        else:
            document.title = title
            document.content_hash = doc_hash
            document.updated_at = func.now()
            report.documents_updated += 1
        for row in stale:
            await db.delete(row)
        await db.flush()
        # Two steps through negative positions keep (document_id, position) unique.
        for position, row in kept:
            row.position = -1 - position
        await db.flush()
        for position, row in kept:
            row.position = position
        await db.flush()
        db.add_all(
            KbChunk(
                document_id=document.id,
                position=position,
                section=chunk.section,
                text=chunk.text,
                content_hash=chunk.content_hash,
                embedding=vector,
            )
            for (position, chunk), vector in zip(fresh, vectors, strict=True)
        )

    report.chunks_embedded += len(fresh)
    report.chunks_reused += len(kept)
    report.chunks_deleted += len(stale)
    log.info(
        "kb_document_ingested",
        source_path=source_path,
        chunks=len(chunks),
        embedded=len(fresh),
        reused=len(kept),
        deleted=len(stale),
    )


def _match(
    chunks: Sequence[Chunk], stored: dict[str, list[KbChunk]]
) -> tuple[list[tuple[int, KbChunk]], list[tuple[int, Chunk]]]:
    """Pair new chunks with stored rows of the same hash; pops matched rows from ``stored``."""
    kept: list[tuple[int, KbChunk]] = []
    fresh: list[tuple[int, Chunk]] = []
    for position, chunk in enumerate(chunks):
        rows = stored.get(chunk.content_hash)
        if rows:
            kept.append((position, rows.pop(0)))
        else:
            fresh.append((position, chunk))
    return kept, fresh


def _title(chunks: Sequence[Chunk], default: str) -> str:
    first_line = chunks[0].text.partition("\n")[0] if chunks else ""
    return first_line.removeprefix("# ").strip() or default


def _report_fields(report: IngestReport) -> dict[str, object]:
    return {name: getattr(report, name) for name in IngestReport.__slots__}


def build_embedder(settings: Settings, *, fake: bool = False) -> Embedder:
    if fake:
        return FakeEmbedder()
    if settings.openai_api_key is None:
        raise RuntimeError("OPENAI_API_KEY is not set; pass --fake for offline vectors")
    return OpenAIEmbedder.create(settings.openai_api_key, settings.embedding_model)


async def _main(argv: Sequence[str]) -> int:
    parser = argparse.ArgumentParser(prog="python -m rozmova_engine.rag.ingest")
    parser.add_argument("kb_dir", nargs="?", type=Path, help="defaults to ROZMOVA_KB_PATH")
    parser.add_argument(
        "--fake", action="store_true", help="deterministic offline vectors (no search quality)"
    )
    args = parser.parse_args(argv)

    settings = Settings()
    configure_logging(settings)
    embedder = build_embedder(settings, fake=args.fake)
    engine = create_engine(settings)
    try:
        await ingest_directory(args.kb_dir or settings.kb_path, engine, embedder)
    finally:
        await engine.dispose()
        if isinstance(embedder, OpenAIEmbedder):
            log.info("kb_embedding_usage", model=embedder.model, tokens=embedder.usage_tokens)
            await embedder.aclose()
    return 0


def main() -> None:
    sys.exit(asyncio.run(_main(sys.argv[1:])))


if __name__ == "__main__":
    main()
